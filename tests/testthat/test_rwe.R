})

test_that('data quality and outcomes work', {
  df <- data.frame(a=c(1,NA,3), b=c(NA,2,3))
  comp <- data_completeness(df)
  expect_equal(names(comp), c('a','b'))
  rules <- list(a=quote(a>0))
  val <- data_validate(df, rules)
  expect_equal(length(val),3)
  out <- detect_outliers_iqr(c(1,2,100))
  expect_equal(which(out),3)
  expect_true(temporal_consistency(as.Date('2020-01-01') + 0:2))
  expect_equal(analyze_prom(c(1,2,3)),2)
  expect_equal(quality_of_life_index(matrix(c(1,2,3,4),ncol=2))[1],1.5)
  mod <- hrqol_model(mpg~cyl, data=mtcars)
  expect_s3_class(mod,'lm')
  pref <- patient_preference(c('a','b','a'))
  expect_equal(pref$Freq[pref$options=='a'],2)
})
