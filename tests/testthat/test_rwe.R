context('Real-world evidence tools')

test_that('cohort selection and matching work', {
  df <- data.frame(id = 1:4, age = c(50,60,70,80), treat = c(1,0,1,0), propensity = c(0.8,0.7,0.2,0.1))
  coh <- select_cohort(df, age > 55)
  expect_equal(nrow(coh), 3)
  mt <- match_cohort(df, caliper = 0.2)
  expect_true(nrow(mt) >= 0)
})

test_that('EHR analytics utilities operate', {
  ehr <- data.frame(patient_id = c(1,2), code = c('E110','A200'), value = c(5,3))
  std <- omop_standardize(ehr)
  expect_equal(names(std), c('person_id','concept_id','value'))
  notes <- c('Patient has diabetes', 'No issues noted')
  terms <- nlp_extract_concepts(notes)
  expect_true('patient' %in% terms$term)
  ph <- phenotype_diabetes(ehr)
  expect_true(any(ph))
  drug <- data.frame(patient_id=c(1,1,2), drug=c('a','a','b'), dose=c(1,2,3))
  exp <- drug_exposure_summary(drug)
  expect_equal(exp$dose[exp$patient_id==1],3)
})

test_that('regulatory helpers check frameworks', {
  report <- c('Safety','Efficacy','Population')
